"""Trace Bell's Fig. 1 (US 186,787) into SVG paths for the line-by-line redraw. Writes site/js/sheet01/bell-fig1.js"""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent / "pylib"))
import numpy as np
from PIL import Image, ImageFilter
import potrace

src = Image.open(Path(__file__).parent / "sources" / "fig1.png").convert("L")
W, H = src.size
UP = 2
img = src.resize((W * UP, H * UP), Image.LANCZOS)
bm = potrace.Bitmap(np.array(img) < 105)
plist = bm.trace(turdsize=60, turnpolicy=potrace.POTRACE_TURNPOLICY_MINORITY, alphamax=1.0, opticurve=True, opttolerance=0.3)
curves = []
for curve in plist:
    sx, sy = curve.start_point.x / UP, curve.start_point.y / UP
    d = [f"M{sx:.1f} {sy:.1f}"]
    pts = [(sx, sy)]
    for seg in curve.segments:
        if seg.is_corner:
            d.append(f"L{seg.c.x/UP:.1f} {seg.c.y/UP:.1f}L{seg.end_point.x/UP:.1f} {seg.end_point.y/UP:.1f}")
            pts += [(seg.c.x/UP, seg.c.y/UP), (seg.end_point.x/UP, seg.end_point.y/UP)]
        else:
            d.append(f"C{seg.c1.x/UP:.1f} {seg.c1.y/UP:.1f} {seg.c2.x/UP:.1f} {seg.c2.y/UP:.1f} {seg.end_point.x/UP:.1f} {seg.end_point.y/UP:.1f}")
            pts += [(seg.end_point.x/UP, seg.end_point.y/UP)]
    d.append("Z")
    xs = [q[0] for q in pts]; ys = [q[1] for q in pts]
    area = 0.5 * sum(pts[i][0] * pts[i - 1][1] - pts[i - 1][0] * pts[i][1] for i in range(len(pts)))
    bw, bh = max(xs) - min(xs), max(ys) - min(ys)
    if bw * bh < 12 or (bw > 0.9 * W and bh > 0.9 * H):
        continue
    curves.append({"d": "".join(d), "x0": min(xs), "y0": min(ys), "x1": max(xs), "y1": max(ys), "area": area, "pts": pts})
# holes vs shapes by nesting depth (this potrace port returns every curve with the same winding)
def inside(pt, poly):
    x, y = pt; c = False
    for i in range(len(poly)):
        (x1, y1), (x2, y2) = poly[i - 1], poly[i]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1 + 1e-12) + x1:
            c = not c
    return c
for c in curves:
    probe = c["pts"][0]
    c["parents"] = [o for o in curves if o is not c and abs(o["area"]) > abs(c["area"])
                    and o["x0"] <= c["x0"] and o["y0"] <= c["y0"] and o["x1"] >= c["x1"] and o["y1"] >= c["y1"] and inside(probe, o["pts"])]
outers = [c for c in curves if len(c["parents"]) % 2 == 0]
holes = [c for c in curves if len(c["parents"]) % 2 == 1]
for o in outers:
    o["holes"] = []
for h in holes:
    cands = [o for o in h["parents"] if len(o["parents"]) % 2 == 0]
    if cands:
        min(cands, key=lambda o: abs(o["area"]))["holes"].append(h)
paths = [{"d": o["d"] + "".join(h["d"] for h in o["holes"]), "x": round(o["x0"], 1), "y": round(o["y0"], 1),
          "w": round(o["x1"] - o["x0"], 1), "h": round(o["y1"] - o["y0"], 1)} for o in outers]
paths.sort(key=lambda p: p["x"])
out = Path(__file__).resolve().parents[1] / "site" / "js" / "sheet01" / "bell-fig1.js"
out.parent.mkdir(parents=True, exist_ok=True)
crop = {"x": 470 - 120, "y": 555 - 160, "w": W, "h": H, "plateW": 1600, "plateH": 1740}
out.write_text("// Traced from A. G. Bell, US Patent 186,787 (1877), sheet 1, Fig. 1 (public domain). Generated by tools/trace_fig1.py\n"
               f"export const FIG1 = {json.dumps({'crop': crop, 'paths': paths})};\n", encoding="utf-8")
print(len(paths), "paths;", out.stat().st_size, "bytes")
